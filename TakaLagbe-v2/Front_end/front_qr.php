<script>
/* Uses the browser's own barcode detector where it is available.
   Nothing is uploaded: the frame never leaves the device. */
(function () {
  var btn = document.getElementById('scanStart');
  var video = document.getElementById('scanVideo');
  var out = document.getElementById('scanResult');
  var stream = null, timer = null;

  if (!('BarcodeDetector' in window) || !navigator.mediaDevices) {
    document.getElementById('scanUnsupported').classList.remove('hide');
    btn.disabled = true;
    return;
  }
  var detector = new BarcodeDetector({ formats: ['qr_code'] });

  function stop() {
    if (timer) { clearInterval(timer); timer = null; }
    if (stream) { stream.getTracks().forEach(function (t) { t.stop(); }); stream = null; }
    video.style.display = 'none';
    btn.textContent = 'Start camera';
  }

  btn.addEventListener('click', function () {
    if (stream) { stop(); return; }
    navigator.mediaDevices.getUserMedia({ video: { facingMode: 'environment' } })
      .then(function (s) {
        stream = s; video.srcObject = s; video.play();
        video.style.display = 'block';
        btn.textContent = 'Stop camera';
        timer = setInterval(function () {
          detector.detect(video).then(function (codes) {
            if (!codes.length) return;
            var parts = codes[0].rawValue.split('|');
            if (parts[0] !== 'TKL' || !/^01[3-9]\d{8}$/.test(parts[1])) {
              /* textContent, never innerHTML: the string came off a QR code
                 somebody else printed, so it is untrusted input. */
              out.textContent = 'That is not a ' + <?= json_encode(APP_NAME) ?> + ' code.';
              out.className = 'err';
              return;
            }
            stop();
            var url = 'sendmoney.php?to=' + encodeURIComponent(parts[1]);
            if (parts[3]) url += '&amount=' + encodeURIComponent(parts[3]);
            out.textContent = 'Found ' + (parts[2] || parts[1]) + '. Opening…';
            location.href = url;
          }).catch(function () {});
        }, 350);
      })
      .catch(function () {
        out.innerHTML = '<span class="err">Camera permission was refused.</span>';
      });
  });
})();
</script>

